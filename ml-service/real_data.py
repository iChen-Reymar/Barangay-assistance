def roster_households(rng: random.Random | None = None) -> list[dict]:
    """One household draw per real roster member.

    The socioeconomic draw is imputed. The identity fields are real.
    Each draw is seeded by the member's name and association, so scoring
    that same blank roster row later uses the identical estimate.
    """
    del rng
    households = []
    for association, members in REAL_ROSTERS.items():
        for member in members:
            household = sample_household(
                household_rng(member["name"], association),
                profile=sampling_profile(association),
            )
            household["name"] = member["name"]
            household["association"] = association
            household["position"] = member["position"]
            household["_observed"] = list(OBSERVED_FIELDS)
            household["_imputed"] = list(IMPUTED_FIELDS)
            households.append(household)
    return households


def roster_summary() -> dict:
    associations: dict[str, int] = {}
    positions: dict[str, int] = {}
    for association, members in REAL_ROSTERS.items():
        associations[association] = len(members)
        for member in members:
            position = member["position"]
            positions[position] = positions.get(position, 0) + 1
    return {
        "members": sum(associations.values()),
        "associations": associations,
        "positions": positions,
        "observedFields": list(OBSERVED_FIELDS),
        "imputedFields": list(IMPUTED_FIELDS),
    }
