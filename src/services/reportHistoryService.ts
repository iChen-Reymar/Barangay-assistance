import {
  reportTemplates,
  type ReportFormat,
  type ReportHistoryEntry,
  type ReportHistoryType,
  type ReportTemplate,
} from '../data/mockData'
import { formatAuditDate } from './auditStorage'
import { datasetForReport, workbookSheets, type ReportSheet } from './reportDatasets'
import { downloadCsv, downloadSectionedCsv, formatExportDateStamp } from '../utils/csvExport'
import { downloadPdfReport } from '../utils/pdfExport'
import { downloadXlsx } from '../utils/xlsxExport'

const REPORT_HISTORY_KEY = 'barangay_report_history'
const UPDATED_EVENT = 'report-history-updated'

export type ReportPreview = {
  entry: ReportHistoryEntry
  title: string
  summary: string[]
  sheets: ReportSheet[]
}

function readHistory(): ReportHistoryEntry[] {
  const raw = localStorage.getItem(REPORT_HISTORY_KEY)
  if (!raw) return []
  try {
    return JSON.parse(raw) as ReportHistoryEntry[]
  } catch {
    return []
  }
}

function writeHistory(entries: ReportHistoryEntry[]) {
  localStorage.setItem(REPORT_HISTORY_KEY, JSON.stringify(entries))
  window.dispatchEvent(new CustomEvent(UPDATED_EVENT))
}

export function initializeReportHistoryStorage() {}

export function getReportHistory(): ReportHistoryEntry[] {
  initializeReportHistoryStorage()
  return readHistory()
}

export function subscribeReportHistory(callback: () => void) {
  const handler = () => callback()
  window.addEventListener(UPDATED_EVENT, handler)
  return () => window.removeEventListener(UPDATED_EVENT, handler)
}

export function getReportTemplateByTitle(title: string): ReportTemplate | null {
  return reportTemplates.find((template) => template.title === title) ?? null
}

function extensionForFormat(format: ReportFormat): string {
  if (format === 'PDF') return 'pdf'
  if (format === 'EXCEL') return 'xlsx'
  return 'csv'
}

function buildFileName(template: ReportTemplate, format: ReportFormat): string {
  const stamp = formatExportDateStamp()
  return `${template.slug}_${stamp}.${extensionForFormat(format)}`
}

function createHistoryEntry(
  template: ReportTemplate,
  generatedBy: string,
  format: ReportFormat,
  userId?: string,
): ReportHistoryEntry {
  const timestamp = new Date().toISOString()
  return {
    id: crypto.randomUUID(),
    name: buildFileName(template, format),
    generatedBy,
    userId: userId || undefined,
    date: formatAuditDate(timestamp),
    format,
    reportType: template.reportType,
  }
}

function prependHistory(entry: ReportHistoryEntry): ReportHistoryEntry {
  writeHistory([entry, ...readHistory()])
  return entry
}

export function generateReportFromTemplate(
  template: ReportTemplate,
  generatedBy: string,
  userId?: string,
): ReportHistoryEntry {
  return prependHistory(createHistoryEntry(template, generatedBy, 'PDF', userId))
}

export function exportReportFromTemplate(
  template: ReportTemplate,
  generatedBy: string,
  format: ReportFormat,
  userId?: string,
): ReportHistoryEntry {
  const entry = prependHistory(createHistoryEntry(template, generatedBy, format, userId))
  downloadHistoryReport(entry)
  return entry
}

function entryById(id: string): ReportHistoryEntry | null {
  return getReportHistory().find((row) => row.id === id) ?? null
}

export function buildReportPreview(entry: ReportHistoryEntry): ReportPreview {
  const dataset = datasetForReport(entry)
  return {
    entry,
    title: dataset.title,
    summary: dataset.summary,
    sheets: dataset.sheets,
  }
}

export function getReportPreviewById(id: string): ReportPreview | null {
  const entry = entryById(id)
  if (!entry) return null
  return buildReportPreview(entry)
}

export function downloadHistoryReport(entry: ReportHistoryEntry): void {
  const dataset = datasetForReport(entry)
  const details = [`Generated by ${entry.generatedBy} on ${entry.date}`, ...dataset.summary]
  if (entry.format === 'PDF') {
    downloadPdfReport(entry.name, {
      title: dataset.title,
      details,
      sections: dataset.sheets.map((sheet) => ({
        heading: sheet.name,
        headers: sheet.headers,
        rows: sheet.rows.map((row) => row.map((cell) => String(cell ?? ''))),
      })),
    })
    return
  }
  if (entry.format === 'EXCEL') {
    downloadXlsx(entry.name, workbookSheets(dataset))
    return
  }
  const fileName = entry.name.replace(/\.(pdf|xlsx)$/i, '.csv')
  if (dataset.sheets.length > 1) {
    downloadSectionedCsv(fileName, dataset.sheets)
    return
  }
  const sheet = dataset.sheets[0]
  downloadCsv(fileName, sheet?.headers ?? ['Note'], sheet?.rows ?? [['No records.']])
}

export function reportTypeLabel(type: ReportHistoryType): string {
  switch (type) {
    case 'beneficiary':
      return 'Beneficiary'
    case 'vulnerability':
      return 'Vulnerability'
    case 'assistance':
      return 'Assistance'
    case 'approved':
      return 'Approved Assistance'
    case 'ai_scoring':
      return 'AI Assessment'
    case 'audit':
      return 'Audit Log'
    default:
      return 'Report'
  }
}
